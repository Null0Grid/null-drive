// Package chunker splits data into content-defined chunks with FastCDC
// (Xia et al., USENIX ATC 2016).
//
// Content-defined chunking puts boundaries where the *content* says so
// (where a rolling hash of the last bytes matches a pattern) instead of at
// fixed offsets. Inserting or deleting bytes therefore only changes the
// chunks around the edit: the boundaries after it are found again at the
// same content, so every later chunk keeps its hash. With fixed-size
// chunks, one inserted byte near the start shifts every boundary and
// every chunk after it changes.
//
// FastCDC's ingredients, all implemented here:
//   - the Gear rolling hash: fp = fp<<1 + G[b], one shift and one add per
//     byte, with a 64-byte effective window when testing the high bits;
//   - cut-point skipping: no hashing in the first Min bytes of a chunk;
//   - normalized chunking: a stricter mask (more bits) before the average
//     size and a looser one after, which pulls chunk sizes towards Avg and
//     narrows the size distribution compared with one mask.
//
// The parameters and the gear table are part of the storage format: if
// either changed, the same file would chunk differently and dedup against
// existing data would be lost. They are fixed constants and pinned by
// TestGolden.
package chunker

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"io"
	"math/bits"
)

// Params are chunk size bounds in bytes. Avg must be a power of two.
type Params struct {
	Min, Avg, Max int
}

// Default: 512 KiB minimum, 2 MiB average, 8 MiB maximum.
//
// Smaller chunks dedup more finely but cost a database row, a hash in
// every manifest and an HTTP request each; 2 MiB keeps a 1 GB file at ~500
// chunks (a ~40 KB manifest) while a small edit still re-uploads only
// ~2-4 MB.
var Default = Params{Min: 512 << 10, Avg: 2 << 20, Max: 8 << 20}

// gear is the 256-entry random table of the Gear hash, generated by
// SplitMix64 from a fixed seed so it is reproducible without a 2 KB literal.
var gear = func() (g [256]uint64) {
	x := uint64(0x4e554c4c44524956) // "NULLDRIV"
	for i := range g {
		x += 0x9e3779b97f4a7c15
		z := x
		z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
		z = (z ^ (z >> 27)) * 0x94d049bb133111eb
		g[i] = z ^ (z >> 31)
	}
	return g
}()

// masks returns the strict (small chunks unlikely) and loose masks for
// normalization level 2: log2(Avg)+2 and log2(Avg)-2 high bits.
func (p Params) masks() (strict, loose uint64) {
	n := bits.Len(uint(p.Avg)) - 1 //nolint:gosec // Avg is validated positive
	return ^uint64(0) << (64 - (n + 2)), ^uint64(0) << (64 - (n - 2))
}

func (p Params) valid() bool {
	return p.Min >= 64 && p.Min < p.Avg && p.Avg < p.Max && p.Avg&(p.Avg-1) == 0
}

// Cut returns the length of the first chunk of data. If data is shorter
// than Max and no boundary is found, it returns len(data) (callers that
// are not at end-of-stream should then supply more data).
func (p Params) Cut(data []byte) int {
	n := len(data)
	if n <= p.Min {
		return n
	}
	if n > p.Max {
		n = p.Max
	}
	normal := p.Avg
	if n < normal {
		normal = n
	}
	strict, loose := p.masks()
	var fp uint64
	i := p.Min
	for ; i < normal; i++ {
		fp = (fp << 1) + gear[data[i]]
		if fp&strict == 0 {
			return i + 1
		}
	}
	for ; i < n; i++ {
		fp = (fp << 1) + gear[data[i]]
		if fp&loose == 0 {
			return i + 1
		}
	}
	return n
}

// Chunk is one piece of the stream. Data is only valid until the next
// call to Next.
type Chunk struct {
	Offset int64
	Data   []byte
	Hash   [32]byte
}

// HexHash returns the chunk's SHA-256 as lowercase hex (its storage key).
func (c Chunk) HexHash() string { return hex.EncodeToString(c.Hash[:]) }

// Chunker reads a stream and yields chunks.
type Chunker struct {
	r      io.Reader
	p      Params
	buf    []byte
	start  int // start of unconsumed data in buf
	end    int // end of valid data in buf
	eof    bool
	offset int64
}

// ErrParams is returned by New for invalid parameters.
var ErrParams = errors.New("chunker: invalid parameters")

// New returns a chunker over r.
func New(r io.Reader, p Params) (*Chunker, error) {
	if !p.valid() {
		return nil, ErrParams
	}
	return &Chunker{r: r, p: p, buf: make([]byte, 2*p.Max)}, nil
}

// Next returns the next chunk, or io.EOF after the last one.
func (c *Chunker) Next() (Chunk, error) {
	if c.end-c.start < c.p.Max && !c.eof {
		// Slide the remainder to the front and fill up to 2*Max.
		copy(c.buf, c.buf[c.start:c.end])
		c.end -= c.start
		c.start = 0
		for c.end < len(c.buf) && !c.eof {
			n, err := c.r.Read(c.buf[c.end:])
			c.end += n
			if errors.Is(err, io.EOF) {
				c.eof = true
			} else if err != nil {
				return Chunk{}, err
			}
		}
	}
	if c.start == c.end {
		return Chunk{}, io.EOF
	}
	n := c.p.Cut(c.buf[c.start:c.end])
	data := c.buf[c.start : c.start+n]
	ch := Chunk{Offset: c.offset, Data: data, Hash: sha256.Sum256(data)}
	c.start += n
	c.offset += int64(n)
	return ch, nil
}

// Ref describes a chunk without its data: a manifest entry.
type Ref struct {
	Hash   string `json:"hash"`
	Size   int64  `json:"size"`
	Offset int64  `json:"-"`
}

// Manifest chunks everything from r and returns the chunk list, the
// SHA-256 of the whole stream and its size. fn, if not nil, is called for
// each chunk (e.g. to store it) before the next one is read.
func Manifest(r io.Reader, p Params, fn func(Chunk) error) (refs []Ref, whole string, size int64, err error) {
	c, err := New(r, p)
	if err != nil {
		return nil, "", 0, err
	}
	h := sha256.New()
	for {
		ch, err := c.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, "", 0, err
		}
		h.Write(ch.Data)
		if fn != nil {
			if err := fn(ch); err != nil {
				return nil, "", 0, err
			}
		}
		refs = append(refs, Ref{Hash: ch.HexHash(), Size: int64(len(ch.Data)), Offset: ch.Offset})
		size += int64(len(ch.Data))
	}
	return refs, hex.EncodeToString(h.Sum(nil)), size, nil
}
