// NotesVector is the worked example in docs/NOTES-E2EE.md: a Null Notes
// note uploaded into an encrypted account, every intermediate value
// included so a third-party implementation can find where it diverges.
// scripts/e2ee-reference/nulldrive_e2ee.py reproduces it from the spec.
type NotesVector struct {
	Note        string            `json:"note"`
	Master      string            `json:"master"`
	Subkeys     map[string]string `json:"subkeys"`
	Fingerprint string            `json:"fingerprint"`
	AuthKey     string            `json:"auth_key"`
	AuthHash    string            `json:"auth_hash"`
	Path        string            `json:"path"`
	Segments    []NotesSegment    `json:"segments"`
	EncPath     string            `json:"encrypted_path"`
	Content     string            `json:"content"`
	ContentSHA  string            `json:"content_sha256"`
	FileHash    string            `json:"file_hash"`
	ChunkNonce  string            `json:"chunk_nonce"`
	Sealed      string            `json:"sealed_chunk"`
	ChunkHash   string            `json:"chunk_hash"`
	Commit      json.RawMessage   `json:"commit"`
}

// NotesSegment shows each step of encrypting one path segment.
type NotesSegment struct {
	Plain  string `json:"plain"`
	Padded string `json:"padded"` // hex
	Nonce  string `json:"nonce"`  // hex, the synthetic nonce
	Enc    string `json:"enc"`
}

func sivNonce(key [KeySize]byte, ad string, pt []byte) []byte {
	m := hmac.New(sha256.New, key[:])
	m.Write([]byte(ad))
	m.Write([]byte{0})
	m.Write(pt)
	return m.Sum(nil)[:chacha20poly1305.NonceSizeX]
}

func buildNotesVector(t *testing.T) NotesVector {
	t.Helper()
	master, _ := hex.DecodeString("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f")
	k, err := FromMaster(master)
	if err != nil {
		t.Fatal(err)
	}
	v := NotesVector{
		Note: "Worked example for docs/NOTES-E2EE.md (Null Notes into an encrypted Null Drive). " +
			"Same master key as vectors.json, whose bundle unlocks it with passphrase \"vector passphrase 123\". " +
			"Generated by go test ./shared/e2ee -run TestNotesVector -update; checked by Go and by scripts/e2ee-reference.",
		Master: hex.EncodeToString(master), Fingerprint: k.Fingerprint(), AuthKey: k.AuthKey(), AuthHash: AuthHash(k.AuthKey()),
		Subkeys: map[string]string{
			"name-enc": hex.EncodeToString(k.nameEnc[:]), "name-siv": hex.EncodeToString(k.nameSIV[:]),
			"chunk-enc": hex.EncodeToString(k.chunkEnc[:]), "chunk-siv": hex.EncodeToString(k.chunkSIV[:]),
			"file-hash": hex.EncodeToString(k.fileHash[:]), "auth": hex.EncodeToString(k.auth[:]),
			"fingerprint": hex.EncodeToString(k.fingerprnt[:]),
		},
		Path: "Null Notes/Work/Plan.md",
	}
	for _, seg := range strings.Split(v.Path, "/") {
		padded := append([]byte(seg), 0x80)
		for len(padded)%namePad != 0 {
			padded = append(padded, 0)
		}
		enc, err := k.EncryptName(seg)
		if err != nil {
			t.Fatal(err)
		}
		v.Segments = append(v.Segments, NotesSegment{Plain: seg, Padded: hex.EncodeToString(padded),
			Nonce: hex.EncodeToString(sivNonce(k.nameSIV, adName, padded)), Enc: enc})
	}
	if v.EncPath, err = k.EncryptPath(v.Path); err != nil {
		t.Fatal(err)
	}
	v.Content = "---\nid: 3f2504e0-4f89-11d3-9a0c-0305e82c3301\n---\n# Plan\nShip the encrypted sync.\n"
	sum := sha256.Sum256([]byte(v.Content))
	v.ContentSHA = hex.EncodeToString(sum[:])
	v.FileHash = k.FileHash(sum[:])
	v.ChunkNonce = hex.EncodeToString(sivNonce(k.chunkSIV, adChunk, []byte(v.Content)))
	sealed := k.SealChunk([]byte(v.Content))
	v.Sealed = hex.EncodeToString(sealed)
	ch := sha256.Sum256(sealed)
	v.ChunkHash = hex.EncodeToString(ch[:])
	commit, _ := json.Marshal(map[string]any{
		"size": len(v.Content), "sha256": v.FileHash, "mtime": "2026-10-18T08:00:00Z",
		"chunks": []map[string]any{{"hash": v.ChunkHash, "size": len(sealed)}},
	})
	v.Commit = commit
	return v
}

func TestNotesVector(t *testing.T) {
	const file = "testdata/notes-vector.json"
	got := buildNotesVector(t)
	if *update {
		b, _ := json.MarshalIndent(got, "", "  ")
		if err := os.WriteFile(file, append(b, '\n'), 0o644); err != nil { //nolint:gosec // test fixture
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	var want NotesVector
	if err := json.Unmarshal(b, &want); err != nil {
		t.Fatal(err)
	}
	g, _ := json.Marshal(got)
	w, _ := json.Marshal(want)
	if !bytes.Equal(g, w) {
		t.Fatalf("notes vector changed: the encryption format is fixed (run with -update only for a new format version)\n got %s\nwant %s", g, w)
	}
	// It decrypts back, and the chunk passes the server's size check.
	k, _ := FromMaster(mustHex(t, want.Master))
	if p, err := k.DecryptPath(want.EncPath); err != nil || p != want.Path {
		t.Fatalf("decrypt path: %q %v", p, err)
	}
	sealed := mustHex(t, want.Sealed)
	if pt, err := k.OpenChunk(sealed); err != nil || string(pt) != want.Content {
		t.Fatalf("open chunk: %v", err)
	}
	if len(sealed)-ChunkOverhead != len(want.Content) {
		t.Fatal("overhead")
	}
	// Same master key as vectors.json, whose bundle unlocks to it.
	var vv Vectors
	vb, _ := os.ReadFile("testdata/vectors.json")
	_ = json.Unmarshal(vb, &vv)
	if vv.Master != want.Master {
		t.Fatal("vectors.json and notes-vector.json must share the master key")
	}
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
