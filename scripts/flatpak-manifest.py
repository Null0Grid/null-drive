#!/usr/bin/env python3
"""Writes the Flatpak manifest for the Null Drive desktop app.

    # Flathub: sources are the release's .tar.gz files (x86_64 + aarch64),
    # pinned by SHA256SUMS.txt
    scripts/flatpak-manifest.py 5.1.1 --sums dist/SHA256SUMS.txt > dev.nullgrid.NullDrive.yml

    # local build (CI, scripts/build-flatpak.sh): one arch, a local tarball
    scripts/flatpak-manifest.py 5.1.1 --local dist/nulldrive-desktop_5.1.1_linux_amd64.tar.gz

The app is the same binary as the .deb/.rpm/AppImage, linked against
WebKitGTK 4.1 and GTK 3, which the GNOME runtime provides. The manifest only
installs it under Flatpak's naming rules (everything called by the app id).
Standard library only, so it runs anywhere CI does.
"""
import argparse
import os
import re
import sys

APP_ID = "dev.nullgrid.NullDrive"
# The GNOME runtime that still ships WebKitGTK 4.1 (libwebkit2gtk-4.1.so.0).
# CI checks the library is there before building.
RUNTIME_VERSION = os.environ.get("FLATPAK_RUNTIME_VERSION", "49")
REPO = "https://github.com/Null0Grid/null-drive"
ARCHES = {"x86_64": "amd64", "aarch64": "arm64"}

# Sandbox permissions, each for one feature.
FINISH_ARGS = [
    ("--share=ipc", "X11 shared memory"),
    ("--share=network", "talking to your server; finding it on the LAN (mDNS)"),
    ("--socket=fallback-x11", "the window, where there's no Wayland"),
    ("--socket=wayland", "the window"),
    ("--device=dri", "GPU rendering in WebKitGTK"),
    # Only the default sync folder. Another folder: flatpak override --user
    # --filesystem=<folder> dev.nullgrid.NullDrive (docs/INSTALL.md).
    ("--filesystem=~/NullDrive:create", "the sync folder"),
    ("--talk-name=org.freedesktop.secrets", "the device token in your keyring (Secret Service)"),
    # The tray registers with the watcher under the app's unique bus name;
    # it needs no well-known name of its own. Single instance doesn't use
    # D-Bus inside Flatpak (client/ipc_linux.go), so no --own-name at all.
    ("--talk-name=org.kde.StatusNotifierWatcher", "the tray icon"),
]

BUILD_COMMANDS = [
    "install -Dm755 nulldrive-desktop /app/bin/nulldrive-desktop",
    f"install -Dm644 nulldrive-desktop.desktop /app/share/applications/{APP_ID}.desktop",
    f"desktop-file-edit --set-icon={APP_ID} /app/share/applications/{APP_ID}.desktop",
    f"install -Dm644 nulldrive-desktop.png /app/share/icons/hicolor/512x512/apps/{APP_ID}.png",
    f"install -Dm644 {APP_ID}.metainfo.xml /app/share/metainfo/{APP_ID}.metainfo.xml",
    f"install -Dm644 LICENSE /app/share/licenses/{APP_ID}/LICENSE",
]


def q(s):
    """YAML double-quoted scalar."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def manifest(version, sources):
    out = [
        f"# Flatpak manifest for Null Drive {version}, generated by scripts/flatpak-manifest.py.",
        "# Sources are the release's prebuilt .tar.gz files (the same binary as the",
        "# .deb, .rpm and AppImage), so the build needs no network or toolchain.",
        f"app-id: {APP_ID}",
        "runtime: org.gnome.Platform",
        f"runtime-version: {q(RUNTIME_VERSION)}",
        "sdk: org.gnome.Sdk",
        "command: nulldrive-desktop",
        "finish-args:",
    ]
    for arg, why in FINISH_ARGS:
        out.append(f"  # {why}")
        out.append(f"  - {arg}")
    out += [
        "modules:",
        "  - name: nulldrive-desktop",
        "    buildsystem: simple",
        "    build-commands:",
    ]
    out += [f"      - {q(c)}" for c in BUILD_COMMANDS]
    out.append("    sources:")
    for s in sources:
        out.append("      - type: archive")
        for k in ("url", "path", "sha256"):
            if k in s:
                out.append(f"        {k}: {q(s[k])}")
        if "arch" in s:
            out.append(f"        only-arches: [{s['arch']}]")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("version")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--sums", help="SHA256SUMS.txt of the release (Flathub manifest)")
    g.add_argument("--local", help="a local nulldrive-desktop_<v>_linux_<arch>.tar.gz")
    a = ap.parse_args()
    version = a.version.removeprefix("v")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?", version):
        sys.exit(f"not a version: {version}")

    if a.local:
        if not os.path.isfile(a.local):
            sys.exit(f"missing {a.local}")
        sources = [{"path": os.path.abspath(a.local)}]
    else:
        sums = {}
        with open(a.sums) as f:
            for line in f:
                h, name = line.split()
                sums[name] = h
        sources = []
        for fp_arch, deb_arch in ARCHES.items():
            name = f"nulldrive-desktop_{version}_linux_{deb_arch}.tar.gz"
            if name not in sums:
                sys.exit(f"{name} is not in {a.sums}")
            sources.append({
                # RELEASE_TAG: the git tag, when it has a "v" (v5.1.1)
                "url": f"{REPO}/releases/download/{os.environ.get('RELEASE_TAG') or version}/{name}",
                "sha256": sums[name],
                "arch": fp_arch,
            })
    sys.stdout.write(manifest(version, sources))


if __name__ == "__main__":
    main()
