#!/usr/bin/env python3
"""Writes the AUR packages for a release: PKGBUILDs and their files.

    scripts/aur.py 5.1.1 dist        → dist/aur/nulldrive-bin/, dist/aur/nulldrive-desktop-bin/

  nulldrive-bin           the server: systemd service as the "nulldrive" user,
                          data in /var/lib/nulldrive, settings in /etc/conf.d/nulldrive
  nulldrive-desktop-bin   the desktop app (needs webkit2gtk-4.1)

Both repackage the release's .tar.gz files (-bin is the AUR's suffix for
prebuilt binaries). The checksums are those of the files in dist/; an
architecture whose archive isn't there is left out (CI builds only x86_64).
.SRCINFO is written by scripts/build-aur.sh with makepkg itself.
Standard library only.
"""
import hashlib
import os
import re
import sys

REPO = "https://github.com/Null0Grid/null-drive"
ARCHES = {"x86_64": "amd64", "aarch64": "arm64"}

SERVICE = """\
[Unit]
Description=Null Drive
Documentation=https://github.com/Null0Grid/null-drive
After=network-online.target
Wants=network-online.target

[Service]
User=nulldrive
Group=nulldrive
EnvironmentFile=-/etc/conf.d/nulldrive
ExecStart=/usr/bin/nulldrive
Restart=on-failure
TimeoutStopSec=35
# Hardening
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=/var/lib/nulldrive
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
CapabilityBoundingSet=

[Install]
WantedBy=multi-user.target
"""

CONF = """\
# Null Drive settings (docs/INSTALL.md, Configuration). Restart after a change:
#   sudo systemctl restart nulldrive
NULLDRIVE_DATA_DIR=/var/lib/nulldrive
NULLDRIVE_PORT=8080
NULLDRIVE_LOG_LEVEL=info
# NULLDRIVE_TRUST_PROXY=on          behind a reverse proxy (Caddy, nginx, Cloudflare Tunnel)
# NULLDRIVE_SEARCH_ORIGINS=https://search.nullgrid.dev
# NULLDRIVE_MDNS=off                don't announce the server on the LAN
"""

SYSUSERS = 'u nulldrive - "Null Drive" /var/lib/nulldrive\n'
TMPFILES = "d /var/lib/nulldrive 0750 nulldrive nulldrive -\n"

INSTALL = """\
post_install() {
  echo "Start Null Drive with: sudo systemctl enable --now nulldrive"
  echo "Then open http://localhost:8080 and create the admin account."
  echo "Settings: /etc/conf.d/nulldrive. Data: /var/lib/nulldrive."
}

post_upgrade() {
  echo "Restart to use the new version: sudo systemctl try-restart nulldrive"
}

post_remove() {
  echo "Your files and settings are still in /var/lib/nulldrive (not deleted)."
}
"""


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def arr(items):
    return "(" + " ".join(f"'{i}'" for i in items) + ")"


def pkgbuild(name, desc, tag, arches, archive, depends, optdepends, extra, local, package_body, header):
    pkgver = tag.replace("-", "_")  # pacman versions can't contain "-"
    lines = [
        header,
        f"pkgname={name}",
        f"pkgver={pkgver}",
        f"_tag={tag}",
        # The release's git tag (5.1.1 or v5.1.1): the download URL's folder.
        f"_release={os.environ.get('RELEASE_TAG') or tag}",
        "pkgrel=1",
        f"pkgdesc='{desc}'",
        f"arch={arr(arches)}",
        "url='https://nullgrid.dev'",
        "license=('LicenseRef-proprietary')",
    ]
    if depends:
        lines.append(f"depends={arr(depends)}")
    if optdepends:
        lines.append(f"optdepends={arr(optdepends)}")
    lines += extra
    if local:
        lines.append(f"source={arr(n for n, _ in local)}")
        lines.append(f"sha256sums={arr(h for _, h in local)}")
    for fp_arch in arches:
        a = ARCHES[fp_arch]
        n, h = archive[fp_arch]
        lines.append(f'source_{fp_arch}=("{name}-${{pkgver}}-{fp_arch}.tar.gz::'
                     f'{REPO}/releases/download/${{_release}}/{n.replace(tag, "${_tag}")}")')
        lines.append(f"sha256sums_{fp_arch}=('{h}')")
    lines += ["", "package() {", "  local a", "  case $CARCH in x86_64) a=amd64 ;; aarch64) a=arm64 ;; esac"]
    lines += package_body
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tag = sys.argv[1].removeprefix("v")
    dist = sys.argv[2]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?", tag):
        sys.exit(f"not a version: {tag}")
    header = (f"# Generated by scripts/aur.py for Null Drive {tag} "
              f"({REPO}). Edit the generator, not this file.\n"
              "# Maintainer: NULLGRID <noreply@nullgrid.dev>")

    def archives(prefix):
        found = {}
        for fp_arch, a in ARCHES.items():
            n = f"{prefix}_{tag}_linux_{a}.tar.gz"
            p = os.path.join(dist, n)
            if os.path.isfile(p):
                found[fp_arch] = (n, sha256(p))
        if not found:
            sys.exit(f"no {prefix}_{tag}_linux_*.tar.gz in {dist}")
        return found

    # --- server ---
    out = os.path.join(dist, "aur", "nulldrive-bin")
    os.makedirs(out, exist_ok=True)
    files = {
        "nulldrive.service": SERVICE,
        "nulldrive.conf": CONF,
        "nulldrive.sysusers": SYSUSERS,
        "nulldrive.tmpfiles": TMPFILES,
        "nulldrive-bin.install": INSTALL,
    }
    for n, c in files.items():
        with open(os.path.join(out, n), "w") as f:
            f.write(c)
    local = [(n, sha256(os.path.join(out, n))) for n in files if n != "nulldrive-bin.install"]
    srv = archives("nulldrive")
    with open(os.path.join(out, "PKGBUILD"), "w") as f:
        f.write(pkgbuild(
            "nulldrive-bin",
            "Null Drive: self-hosted file sync server with a built-in web app",
            tag, list(srv), srv, [], [],
            ["provides=('nulldrive')", "conflicts=('nulldrive')",
             "backup=('etc/conf.d/nulldrive')", "install=nulldrive-bin.install"],
            local,
            [
                '  local d="nulldrive_${_tag}_linux_$a"',
                '  install -Dm755 "$d/nulldrive" "$pkgdir/usr/bin/nulldrive"',
                '  install -Dm644 "$d/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"',
                '  install -Dm644 nulldrive.service "$pkgdir/usr/lib/systemd/system/nulldrive.service"',
                '  install -Dm644 nulldrive.sysusers "$pkgdir/usr/lib/sysusers.d/nulldrive.conf"',
                '  install -Dm644 nulldrive.tmpfiles "$pkgdir/usr/lib/tmpfiles.d/nulldrive.conf"',
                '  install -Dm644 nulldrive.conf "$pkgdir/etc/conf.d/nulldrive"',
            ],
            header,
        ))

    # --- desktop app ---
    out = os.path.join(dist, "aur", "nulldrive-desktop-bin")
    os.makedirs(out, exist_ok=True)
    app = archives("nulldrive-desktop")
    with open(os.path.join(out, "PKGBUILD"), "w") as f:
        f.write(pkgbuild(
            "nulldrive-desktop-bin",
            "Null Drive desktop app: keeps a folder in sync with your own Null Drive server",
            tag, list(app), app,
            ["webkit2gtk-4.1", "gtk3", "xdg-utils"],
            ["gnome-keyring: keeps the sign-in (or KWallet, any Secret Service keyring)",
             "libappindicator-gtk3: tray icon on GNOME with the AppIndicator extension"],
            ["provides=('nulldrive-desktop')", "conflicts=('nulldrive-desktop')"],
            [],
            [
                '  local d="nulldrive-desktop_${_tag}_linux_$a"',
                '  install -Dm755 "$d/nulldrive-desktop" "$pkgdir/usr/bin/nulldrive-desktop"',
                '  install -Dm644 "$d/nulldrive-desktop.desktop" "$pkgdir/usr/share/applications/nulldrive-desktop.desktop"',
                '  install -Dm644 "$d/nulldrive-desktop.png" "$pkgdir/usr/share/icons/hicolor/512x512/apps/nulldrive-desktop.png"',
                '  install -Dm644 "$d/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"',
            ],
            header,
        ))
    print(os.path.join(dist, "aur"))


if __name__ == "__main__":
    main()
